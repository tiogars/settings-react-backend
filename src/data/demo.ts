let seq = 0
export function nextId(prefix: string): string {
  seq += 1
  return `${prefix}-${seq.toString(36)}-${Date.now().toString(36)}`
}

const now = Date.now()
function daysAgo(days: number): string {
  return new Date(now - days * 86_400_000).toISOString()
}

